export function illustration(t,opts){
  validateTable(t);const warnings=tableWarnings(t);if(warnings.length)throw new Error(warnings.join(' '));
  const {xmin,xmax,ymin,ymax}=opts,xs=t.points.map(p=>numericLabel(p.x));
  const leftValues=t.points.map(p=>numericLabel(p.y)),rightValues=t.points.map(p=>numericLabel(rightValue(p)));
  if([...leftValues,...rightValues].some(Number.isNaN))throw new Error('Phác họa cần y là số, biểu thức số hoặc ±∞. Nhãn tự do chỉ dùng trong bảng.');
  const ex={source:'Đường cong minh họa từ bảng — không xác định duy nhất',evaluate(x){
    const i=xs.findIndex((v,j)=>j<xs.length-1&&x>v&&x<xs[j+1]);if(i<0||t.signs[i]==='||')return NaN;
    const a=Number.isFinite(xs[i])?xs[i]:xmin,b=Number.isFinite(xs[i+1])?xs[i+1]:xmax;
    const rawA=rightValues[i],rawB=leftValues[i+1];
    if(Number.isNaN(rawA)||Number.isNaN(rawB))return NaN;
    const av=Number.isFinite(rawA)?rawA:rawA>0?ymax:ymin,bv=Number.isFinite(rawB)?rawB:rawB>0?ymax:ymin;
    const u=Math.max(0,Math.min(1,(x-a)/(b-a)));return av+(bv-av)*(3*u*u-2*u*u*u);
  }};
  return graph(ex,null,{...opts,title:'Phác họa minh họa từ bảng biến thiên'});
}
export function parseTree(source){
  const lines=source.split('\n').filter(x=>x.trim());if(!lines.length||lines.length>31)throw new Error('Sơ đồ cần 1–31 nút.');
  const nodes=[],stack=[];
  lines.forEach((raw,i)=>{
    if(raw.includes('\t'))throw new Error('Dùng 2 dấu cách cho mỗi cấp, không dùng Tab.');
    const spaces=raw.length-raw.trimStart().length,depth=spaces/2;
    if(!Number.isInteger(depth)||depth>5||(i===0&&depth!==0)||(i>0&&depth===0)||depth>stack.length)throw new Error(`Dòng ${i+1}: mỗi cấp thụt 2 dấu cách, chỉ có một nút gốc.`);
    const [label,...rest]=raw.trim().split('|'),edge=rest.join('|').trim();if(!label.trim()||label.length>28||edge.length>20)throw new Error('Tên nút tối đa 28 ký tự, nhãn nhánh tối đa 20 ký tự.');
    const node={label:label.trim(),edge,depth,children:[]};if(depth)stack[depth-1].children.push(node);nodes.push(node);stack[depth]=node;stack.length=depth+1;
  });return {root:nodes[0],nodes};
}
export function tree(source,{color='#2755df',title='Sơ đồ cây'}={}){
  const {root,nodes}=parseTree(source),leaves=nodes.filter(n=>!n.children.length).length,height=Math.max(430,leaves*64+100),s=scene(900,height),depth=Math.max(1,...nodes.map(n=>n.depth));let k=0;
  const layout=n=>{n.x=90+n.depth*(720/depth);n.y=n.children.length?(n.children.forEach(layout),n.children.reduce((v,c)=>v+c.y,0)/n.children.length):90+(++k-.5)*(height-130)/leaves;};layout(root);
  text(s,450,32,title||'Sơ đồ cây',22);
  nodes.forEach(n=>n.children.forEach(c=>{line(s,n.x+48,n.y,c.x-48,c.y,'#9aaccb',1.4);if(c.edge)text(s,(n.x+c.x)/2,(n.y+c.y)/2-12,c.edge,15,muted);}));
  nodes.forEach(n=>{rect(s,n.x-48,n.y-19,96,38,n===root?color:'#f0f4ff',n===root?color:'#dbe3f3');text(s,n.x,n.y,n.label,Math.min(16,140/n.label.length+6),n===root?'#ffffff':ink);});return s;
}
