export function scene(width=900,height=540){return {width,height,items:[]};}
function line(s,x1,y1,x2,y2,color=ink,width=1.3,dash=false){s.items.push({type:'line',x1,y1,x2,y2,color,width,dash});}
function text(s,x,y,label,size=18,color=ink,anchor='middle'){s.items.push({type:'text',x,y,label:String(label),size,color,anchor});}
function rect(s,x,y,w,h,fill,stroke=fill){s.items.push({type:'rect',x,y,w,h,fill,stroke});}
function dot(s,x,y,r=4,color='#2755df',open=false){s.items.push({type:'circle',x,y,r,color,open});}
function arrow(s,x1,y1,x2,y2,color=ink,width=1.8){line(s,x1,y1,x2,y2,color,width);const a=Math.atan2(y2-y1,x2-x1),l=8;line(s,x2,y2,x2-l*Math.cos(a-.45),y2-l*Math.sin(a-.45),color,width);line(s,x2,y2,x2-l*Math.cos(a+.45),y2-l*Math.sin(a+.45),color,width);}
function polyline(s,points,color,width=2.3){if(points.length>1)s.items.push({type:'polyline',points:simplify(points),color,width});}
export function toSVG(s){
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${s.width}" height="${s.height}" viewBox="0 0 ${s.width} ${s.height}" role="img" aria-label="Hình vẽ toán học"><rect width="100%" height="100%" fill="white"/>${s.items.map(p=>{
    if(p.type==='line')return `<line x1="${f(p.x1)}" y1="${f(p.y1)}" x2="${f(p.x2)}" y2="${f(p.y2)}" stroke="${p.color}" stroke-width="${p.width}" ${p.dash?'stroke-dasharray="5 5"':''}/>`;
    if(p.type==='text'&&mathLabel(p.label)){const m=mathLabel(p.label),w=m.width*p.size,h=m.height*p.size,x=p.anchor==='middle'?p.x-w/2:p.anchor==='end'?p.x-w:p.x;return `<svg x="${f(x)}" y="${f(p.y-h/2)}" width="${w}" height="${h}" viewBox="${m.viewBox.join(' ')}" color="${p.color}" fill="${p.color}">${m.body}</svg>`;}
    if(p.type==='text')return `<text x="${f(p.x)}" y="${f(p.y)}" font-family="Georgia, 'Times New Roman', serif" font-size="${p.size}" fill="${p.color}" text-anchor="${p.anchor}" dominant-baseline="middle">${esc(p.label)}</text>`;
    if(p.type==='rect')return `<rect x="${f(p.x)}" y="${f(p.y)}" width="${p.w}" height="${p.h}" rx="7" fill="${p.fill}" stroke="${p.stroke}"/>`;
    if(p.type==='circle')return `<circle cx="${f(p.x)}" cy="${f(p.y)}" r="${p.r}" fill="${p.open?'white':p.color}" stroke="${p.color}" stroke-width="1.7"/>`;
    return `<polyline points="${p.points.map(([x,y])=>`${f(x)},${f(y)}`).join(' ')}" fill="none" stroke="${p.color}" stroke-width="${p.width}" stroke-linejoin="round" stroke-linecap="round"/>`;
  }).join('')}</svg>`;
}
